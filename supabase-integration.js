// 5. TAMPILKAN NOTIFIKASI (Gunakan yang sudah ada)
// ============================================================
function tampilkanNotifikasi(pesan, jenis = 'berhasil') {
    // Coba gunakan showNotification dari app.js
    if (typeof window.showNotification === 'function') {
        window.showNotification(pesan, jenis === 'berhasil' ? 'success' : 'error');
        return;
    }
    
    // Fallback: buat notifikasi sendiri
    let notif = document.getElementById('notifSupabase');
    if (!notif) {
        notif = document.createElement('div');
        notif.id = 'notifSupabase';
        notif.style.cssText = `
            position: fixed;
            bottom: 100px;
            left: 50%;
            transform: translateX(-50%);
            padding: 10px 24px;
            border-radius: 30px;
            font-size: 13px;
            font-weight: bold;
            z-index: 10000;
            display: none;
            box-shadow: 0 4px 15px rgba(0,0,0,0.3);
            max-width: 90%;
            text-align: center;
        `;
        document.body.appendChild(notif);
    }
    
    if (jenis === 'berhasil') {
        notif.style.backgroundColor = '#2ecc71';
        notif.style.color = '#0a1a0a';
        notif.innerHTML = '✅ ' + pesan;
    } else {
        notif.style.backgroundColor = '#e74c3c';
        notif.style.color = 'white';
        notif.innerHTML = '❌ ' + pesan;
    }
    
    notif.style.display = 'block';
    clearTimeout(notif._timer);
    notif._timer = setTimeout(() => {
        notif.style.display = 'none';
    }, 3000);
}

