// 6. TOMBOL LIHAT LAPORAN
// ============================================================
function tambahTombolLihatLaporan() {
    const actionButtons = document.querySelector('.action-buttons');
    if (!actionButtons) {
        setTimeout(tambahTombolLihatLaporan, 1000);
        return;
    }
    
    if (document.getElementById('btnLihatLaporanSupabase')) return;
    
    const btn = document.createElement('button');
    btn.id = 'btnLihatLaporanSupabase';
    btn.innerHTML = '<i class="fas fa-database"></i> 📋 LIHAT LAPORAN';
    btn.style.cssText = `
        background: #3498db;
        margin-top: 10px;
        color: white;
        border: none;
        border-radius: 8px;
        padding: 10px 15px;
        font-weight: bold;
        font-size: 14px;
        cursor: pointer;
        transition: all 0.2s;
        flex: 1;
        min-width: 140px;
    `;
    btn.onmouseover = function() { this.style.background = '#2980b9'; };
    btn.onmouseout = function() { this.style.background = '#3498db'; };
    
    btn.onclick = async function() {
        if (!supabaseClient || !isSupabaseConnected) {
            tampilkanNotifikasi('Supabase belum siap', 'gagal');
            return;
        }
        
        try {
            const { data, error } = await supabaseClient
                .from(SUPABASE_CONFIG.table)
                .select('*')
                .order('tanggal_kirim', { ascending: false })
                .limit(100);
            
            if (error) throw error;
            
            if (!data || data.length === 0) {
                tampilkanNotifikasi('Belum ada laporan tersimpan', 'gagal');
                return;
            }
            
            tampilkanModalLaporan(data);
            
        } catch (error) {
            console.error('❌ Gagal ambil data:', error);
            tampilkanNotifikasi('Gagal mengambil data: ' + error.message, 'gagal');
        }
    };
    
    actionButtons.appendChild(btn);
    console.log('✅ Tombol Lihat Laporan ditambahkan');
}

