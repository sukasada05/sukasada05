// 4. SIMPAN KE SUPABASE
// ============================================================
async function simpanKeSupabase(data) {
    if (!supabaseClient || !isSupabaseConnected) {
        console.warn('⚠️ Supabase belum siap, data tidak disimpan');
        return { success: false, error: 'Supabase belum siap' };
    }
    
    try {
        const { data: hasil, error } = await supabaseClient
            .from(SUPABASE_CONFIG.table)
            .insert([data]);
        
        if (error) throw error;
        console.log('✅ Data tersimpan di Supabase:', hasil);
        return { success: true, data: hasil };
    } catch (error) {
        console.error('❌ Gagal simpan ke Supabase:', error);
        return { success: false, error: error.message };
    }
}

